import express from 'express';
import { createServer } from 'node:http';
import { Server as SocketServer } from 'socket.io';
import mongoose from 'mongoose';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import dotenv from 'dotenv';
import listingRoutes from './routes/listings.js';
import authRoutes from './routes/auth.js';
import uploadRoutes from './routes/uploads.js';
import conversationRoutes from './routes/conversations.js';
import offerRoutes from './routes/offers.js';
import reportRoutes from './routes/reports.js';
import adminRoutes from './routes/admin.js';
import categoryRoutes from './routes/categories.js';
import transactionRoutes from './routes/transactions.js';
import reviewRoutes from './routes/reviews.js';
import notificationRoutes from './routes/notifications.js';
import { authenticateRealtime, setRealtime } from './services/realtime.js';
import path from 'node:path';
dotenv.config();
const app = express();
app.set('trust proxy', 1);
const clientOrigin = process.env.CLIENT_URL || 'http://localhost:5173';
app.use(cors({ origin: clientOrigin, credentials: true }));
app.use(express.json({ limit: '2mb' }));
app.use(cookieParser());
app.use('/uploads', express.static(path.resolve('uploads'), { fallthrough: false, maxAge: '7d' }));
app.get('/api/health', (_req, res) => res.json({ status: 'ok', app: 'FurniLoop' }));
app.use('/api/auth', authRoutes);
app.use('/api/listings', listingRoutes);
app.use('/api/uploads', uploadRoutes);
app.use('/api/conversations', conversationRoutes);
app.use('/api/offers', offerRoutes);
app.use('/api/reports', reportRoutes);
app.use('/api/admin', adminRoutes);
app.use('/api/categories', categoryRoutes);
app.use('/api/transactions', transactionRoutes);
app.use('/api/reviews', reviewRoutes);
app.use('/api/notifications', notificationRoutes);
app.use('/api', (_req, res) => res.status(404).json({ message: 'API route not found.' }));
if (process.env.NODE_ENV === 'production') {
  app.use(express.static(path.resolve('dist')));
  app.get('*', (_req, res) => res.sendFile(path.resolve('dist/index.html')));
}
const port = process.env.PORT || 5000;
if (process.env.MONGODB_URI) mongoose.connect(process.env.MONGODB_URI).then(() => console.log('MongoDB connected')).catch(err => console.error('MongoDB connection failed:', err.message));
else console.warn('Set MONGODB_URI to enable database-backed features.');
const server = createServer(app);
const io = new SocketServer(server, { cors: { origin: clientOrigin, credentials: true }, transports: ['websocket', 'polling'] });
setRealtime(io);
authenticateRealtime(io);
server.listen(port, () => console.log(`FurniLoop API listening on ${port}`));
